let currentExamQuestions = [];
let currentExamIndex = 0;
let examScore = 0;
let isExamActive = false; 

function startTheoreticalExam() {
    let autoGenerated = generateAutoQuestions();
    
    function shuffle(array) {
        let currentIndex = array.length, randomIndex;
        while (currentIndex != 0) {
            randomIndex = Math.floor(Math.random() * currentIndex);
            currentIndex--;
            [array[currentIndex], array[randomIndex]] = [array[randomIndex], array[currentIndex]];
        }
        return array;
    }
    
    let allLocations = shuffle([...manualExamBank.filter(q => q.cat === 'location'), ...autoGenerated.location]);
    let allElements = shuffle([...manualExamBank.filter(q => q.cat === 'element'), ...autoGenerated.element]);
    let allCycles = shuffle(manualExamBank.filter(q => q.cat === 'cycle'));
    let allSpecials = shuffle([...manualExamBank.filter(q => q.cat === 'special'), ...autoGenerated.special]);
    let allCases = shuffle(manualExamBank.filter(q => q.cat === 'case'));
    let allMisc = shuffle(manualExamBank.filter(q => q.cat === 'misc'));

    let finalExam = [
        ...allLocations.slice(0, 2),
        ...allElements.slice(0, 2),
        ...allCycles.slice(0, 2),
        ...allSpecials.slice(0, 2),
        ...allCases.slice(0, 8),
        ...allMisc.slice(0, 4)
    ];
    
    currentExamQuestions = shuffle(finalExam);
    currentExamIndex = 0;
    examScore = 0;
    isExamActive = true;
    
    const startScreen = document.getElementById('exam-start-screen');
    if(startScreen) startScreen.style.display = 'none';
    
    renderExamQuestion();
}

function resumeExamIfActive() {
    if (isExamActive && currentExamQuestions.length > 0) {
        const startScreen = document.getElementById('exam-start-screen');
        if(startScreen) startScreen.style.display = 'none';
        renderExamQuestion();
    }
}

function endTheoreticalExam() {
    isExamActive = false;
    currentExamQuestions = [];
    currentExamIndex = 0;
    examScore = 0;
    
    const container = document.getElementById('exam-container');
    const startScreen = document.getElementById('exam-start-screen');
    if(container) container.style.display = 'none';
    if(startScreen) startScreen.style.display = 'block';
}

